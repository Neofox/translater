// Command syncicons writes internal/web/icons/icons_gen.go: the SVG child
// elements of every icon named in internal/web/icons/names.txt, taken from
// lucide-static's icon-nodes.json (../node_modules/lucide-static, pinned to
// the lucide-react version the TS app renders). Run via `go generate ./...`
// in go/; the output is deterministic and `make check` fails when it is
// stale.
//
// Hand-written: lucide ships no Go package, and the conversion is a JSON
// walk that keeps each node's attribute order (lucide-react renders the
// attributes in that order).
package main

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"html"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"encoding/json/jsontext"
)

// Entry is one names.txt line.
type Entry struct {
	Name    string
	Aliases []string
}

// ParseNames reads names.txt: `name alias…` per line, `#` comments.
func ParseNames(src string) ([]Entry, error) {
	var out []Entry
	seen := map[string]bool{}
	sc := bufio.NewScanner(strings.NewReader(src))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if seen[fields[0]] {
			return nil, fmt.Errorf("names.txt: %q listed twice", fields[0])
		}
		seen[fields[0]] = true
		out = append(out, Entry{Name: fields[0], Aliases: fields[1:]})
	}
	return out, sc.Err()
}

// Children renders one icon's node list ([[tag, {attr: value…}], …]) as
// markup, attributes in source order, values HTML-escaped.
func Children(node jsontext.Value) (string, error) {
	dec := jsontext.NewDecoder(bytes.NewReader(node))
	var b strings.Builder
	if err := expect(dec, '['); err != nil {
		return "", err
	}
	for dec.PeekKind() != ']' {
		if err := expect(dec, '['); err != nil {
			return "", err
		}
		tag, err := str(dec)
		if err != nil {
			return "", err
		}
		b.WriteString("<" + tag)
		if err := expect(dec, '{'); err != nil {
			return "", err
		}
		for dec.PeekKind() != '}' {
			key, err := str(dec)
			if err != nil {
				return "", err
			}
			tok, err := dec.ReadToken()
			if err != nil {
				return "", err
			}
			var val string
			switch tok.Kind() {
			case '"':
				val = tok.String()
			case '0':
				val = string(tok.String())
			default:
				return "", fmt.Errorf("%s.%s: unsupported attribute value %v", tag, key, tok.Kind())
			}
			fmt.Fprintf(&b, ` %s="%s"`, key, html.EscapeString(val))
		}
		if _, err := dec.ReadToken(); err != nil { // }
			return "", err
		}
		if dec.PeekKind() != ']' {
			return "", fmt.Errorf("%s: nested icon nodes are not supported", tag)
		}
		if _, err := dec.ReadToken(); err != nil { // ]
			return "", err
		}
		b.WriteString("></" + tag + ">")
	}
	return b.String(), nil
}

func expect(dec *jsontext.Decoder, kind jsontext.Kind) error {
	tok, err := dec.ReadToken()
	if err != nil {
		return err
	}
	if tok.Kind() != kind {
		return fmt.Errorf("icon node: got %v, want %v", tok.Kind(), kind)
	}
	return nil
}

func str(dec *jsontext.Decoder) (string, error) {
	tok, err := dec.ReadToken()
	if err != nil {
		return "", err
	}
	if tok.Kind() != '"' {
		return "", fmt.Errorf("icon node: got %v, want a string", tok.Kind())
	}
	return tok.String(), nil
}

// Nodes indexes icon-nodes.json by icon name, keeping each raw node list.
func Nodes(src []byte) (map[string]jsontext.Value, error) {
	dec := jsontext.NewDecoder(bytes.NewReader(src))
	if err := expect(dec, '{'); err != nil {
		return nil, err
	}
	out := map[string]jsontext.Value{}
	for dec.PeekKind() != '}' {
		name, err := str(dec)
		if err != nil {
			return nil, err
		}
		v, err := dec.ReadValue()
		if err != nil {
			return nil, err
		}
		out[name] = v.Clone()
	}
	return out, nil
}

// Generate returns icons_gen.go for entries. lucideDir is the lucide-static
// package; every alias must exist there as icons/<alias>.svg.
func Generate(entries []Entry, nodes map[string]jsontext.Value, lucideDir string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by syncicons from lucide-static 1.61.0 and names.txt. DO NOT EDIT.\n\n")
	b.WriteString("package icons\n\n")
	b.WriteString("var icons = map[string]icon{\n")
	for _, e := range entries {
		node, ok := nodes[e.Name]
		if !ok {
			return nil, fmt.Errorf("lucide-static has no icon %q", e.Name)
		}
		children, err := Children(node)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", e.Name, err)
		}
		for _, a := range e.Aliases {
			if _, err := os.Stat(filepath.Join(lucideDir, "icons", a+".svg")); err != nil {
				return nil, fmt.Errorf("%s: alias %q is not a lucide-static icon", e.Name, a)
			}
		}
		fmt.Fprintf(&b, "\t%q: {aliases: %#v, children: %q},\n", e.Name, e.Aliases, children)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "syncicons:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	out, err := Output(root)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, "internal", "web", "icons", "icons_gen.go"), out, 0o644)
}

// Output is icons_gen.go for the module at root.
func Output(root string) ([]byte, error) {
	lucideDir := filepath.Join(root, "..", "node_modules", "lucide-static")
	src, err := os.ReadFile(filepath.Join(lucideDir, "icon-nodes.json"))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, errors.New("node_modules/lucide-static is missing: run `npm ci` at the repository root")
	} else if err != nil {
		return nil, err
	}
	nodes, err := Nodes(src)
	if err != nil {
		return nil, err
	}
	names, err := os.ReadFile(filepath.Join(root, "internal", "web", "icons", "names.txt"))
	if err != nil {
		return nil, err
	}
	entries, err := ParseNames(string(names))
	if err != nil {
		return nil, err
	}
	return Generate(entries, nodes, lucideDir)
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		} else if !errors.Is(err, fs.ErrNotExist) {
			return "", err
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found above the working directory")
		}
		dir = parent
	}
}
