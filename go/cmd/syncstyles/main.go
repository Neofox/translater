// Command syncstyles copies the TS app's stylesheet into the Go app:
// web/static/css/base.css is ../src/styles.css without its two @import lines
// (input.css imports Tailwind and the fonts itself), and pretendard.css is
// ../src/styles/pretendard.css verbatim. Run via `go generate ./...` in go/;
// the committed copies must stay fresh (TestStylesFresh).
//
// Hand-written: two file reads and writes.
package main

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const header = "/* Code generated by syncstyles from src/styles.css. DO NOT EDIT. */\n"

// dropped are the src/styles.css lines input.css replaces.
var dropped = []string{"@import './styles/pretendard.css';", "@import 'tailwindcss';"}

// Base turns src/styles.css into base.css.
func Base(src string) (string, error) {
	lines := strings.SplitAfter(src, "\n")
	var b strings.Builder
	b.WriteString(header)
	found := 0
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if trimmed == dropped[0] || trimmed == dropped[1] {
			found++
			continue
		}
		b.WriteString(line)
	}
	if found != len(dropped) {
		return "", fmt.Errorf("expected the two @import lines in src/styles.css, found %d", found)
	}
	return b.String(), nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "syncstyles:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	outputs, err := Outputs(root)
	if err != nil {
		return err
	}
	for path, content := range outputs {
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Outputs maps each generated file under root (the Go module) to its
// content.
func Outputs(root string) (map[string]string, error) {
	styles, err := os.ReadFile(filepath.Join(root, "..", "src", "styles.css"))
	if err != nil {
		return nil, err
	}
	base, err := Base(string(styles))
	if err != nil {
		return nil, err
	}
	pretendard, err := os.ReadFile(filepath.Join(root, "..", "src", "styles", "pretendard.css"))
	if err != nil {
		return nil, err
	}
	dir := filepath.Join(root, "web", "static", "css")
	return map[string]string{
		filepath.Join(dir, "base.css"):       base,
		filepath.Join(dir, "pretendard.css"): string(pretendard),
	}, nil
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		} else if !errors.Is(err, fs.ErrNotExist) {
			return "", err
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found above the working directory")
		}
		dir = parent
	}
}
