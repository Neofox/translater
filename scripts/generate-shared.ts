// Generates the TypeScript views of shared/translation/ that cannot be
// imported directly in every runtime (Vite server bundle, tsx scripts,
// promptfoo, vitest):
// - src/server/promptTemplates.generated.json: every prompts/**/*.mustache
//   file by name (bundled like any JSON import; `?raw` and fs reads do not
//   work in all four runtimes).
// - src/server/resultTypes.generated.ts: static types for the strict result
//   JSON Schemas (z.fromJSONSchema validates at runtime but cannot infer
//   types), via json-schema-to-typescript.
// Run `npm run shared:generate` after editing shared/translation/;
// src/server/sharedGenerated.test.ts fails while the outputs are stale.
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'
import type { JSONSchema } from 'json-schema-to-typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const shared = join(root, 'shared/translation')
export const PROMPT_TEMPLATES_PATH = join(
  root,
  'src/server/promptTemplates.generated.json',
)
export const RESULT_TYPES_PATH = join(
  root,
  'src/server/resultTypes.generated.ts',
)

async function mustacheFiles(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true })
  const nested = await Promise.all(
    entries.map((e) =>
      e.isDirectory()
        ? mustacheFiles(join(dir, e.name))
        : Promise.resolve(
            e.name.endsWith('.mustache') ? [join(dir, e.name)] : [],
          ),
    ),
  )
  return nested.flat()
}

/** Template name = path below prompts/ without extension, `/`-separated. */
export async function promptTemplatesSource(): Promise<string> {
  const dir = join(shared, 'prompts')
  const files = (await mustacheFiles(dir)).sort()
  const templates: Record<string, string> = {}
  for (const file of files) {
    const name = relative(dir, file)
      .split(sep)
      .join('/')
      .replace(/\.mustache$/, '')
    templates[name] = await readFile(file, 'utf8')
  }
  return `${JSON.stringify(templates, null, 2)}\n`
}

async function schema(name: string): Promise<JSONSchema> {
  return JSON.parse(
    await readFile(join(shared, `schemas/${name}.json`), 'utf8'),
  ) as JSONSchema
}

export async function resultTypesSource(): Promise<string> {
  const sentence = await schema('sentence')
  const word = await schema('word')
  const phrase = sentence.properties!.learningPhrases!.items as JSONSchema
  const character = phrase.properties!.characters!.items as JSONSchema
  const options = {
    bannerComment: '',
    additionalProperties: false,
    // Plain arrays, not tuple unions; zod enforces the bounds at runtime.
    maxItems: -1,
    style: { semi: false, singleQuote: true, trailingComma: 'all' as const },
  }
  const parts = await Promise.all([
    compile(sentence, 'SentenceResultData', options),
    compile(word, 'WordResultData', options),
    compile(phrase, 'LearningPhraseData', options),
    compile(character, 'CharacterBreakdownData', options),
  ])
  return [
    '// Generated by scripts/generate-shared.ts from',
    '// shared/translation/schemas/*.json. Do not edit; run',
    '// `npm run shared:generate`.',
    '',
    ...parts,
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(PROMPT_TEMPLATES_PATH, await promptTemplatesSource())
  await writeFile(RESULT_TYPES_PATH, await resultTypesSource())
  console.log('[shared] generated prompt templates and result types')
}
